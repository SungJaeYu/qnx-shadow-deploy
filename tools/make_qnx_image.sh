#!/bin/bash
# Build only. Boot and target validation are separate, explicit steps.
set -euo pipefail

project_dir=$(cd "$(dirname "$0")/.." && pwd -P)
build_dir=$project_dir/build-qnx-container
vm_dir=$project_dir/build-qnx-vm
: "${QNX_TARGET:?Source the QNX SDK environment first}"
command -v mkqnximage >/dev/null
command -v ssh-keygen >/dev/null || {
    printf 'ssh-keygen missing. Rebuild the container image first.\n' >&2
    exit 1
}
# These paths become unquoted paths in QNX image buildfile snippets.
case "$project_dir$QNX_TARGET" in
    *[[:space:]\"\#\=]*)
        printf 'Image source paths must not contain whitespace, quotes, # or =.\n' >&2
        exit 2 ;;
esac
targets=(shadow-demo shadow-worker shadow-candidate shadowctl policy-tests staging-tests)
for name in "${targets[@]}"; do
    if [ ! -f "$build_dir/$name" ] ||
       ! file "$build_dir/$name" | grep -q 'interpreter /usr/lib/ldqnx-64.so.2'; then
        printf 'Missing QNX executable: %s. Run the cross-build first.\n' "$name" >&2
        exit 1
    fi
done
if [ ! -f "$build_dir/candidate.manifest" ] ||
   ! grep -qx 'os=qnx' "$build_dir/candidate.manifest" ||
   ! grep -qx 'architecture=x86_64' "$build_dir/candidate.manifest"; then
    printf 'Missing or mismatched QNX candidate manifest.\n' >&2
    exit 1
fi
cxx_runtime=$QNX_TARGET/x86_64/usr/lib/libc++.so.2
if [ ! -f "$cxx_runtime" ]; then
    printf 'Required QNX C++ runtime missing: %s\n' "$cxx_runtime" >&2
    exit 1
fi

mkdir -p "$vm_dir/local/snippets"
# Own one named snippet; preserve user customizations in other snippets.
{
    printf '# Generated by ShadowDeploy tools/make_qnx_image.sh\n'
    printf '[-optional]\n'
    printf '[type=dir uid=0 gid=0 perms=755] bin/shadowdeploy\n'
    for name in "${targets[@]}"; do
        printf '[uid=0 gid=0 perms=555] bin/shadowdeploy/%s=%s/%s\n' \
            "$name" "$build_dir" "$name"
    done
    printf '[uid=0 gid=0 perms=444] bin/shadowdeploy/candidate.manifest=%s/candidate.manifest\n' "$build_dir"
    printf '[uid=0 gid=0 perms=555] bin/shadowdeploy/deployment_hook_example.sh=%s/tools/deployment_hook_example.sh\n' "$project_dir"
    # Explicitly require the C++ runtime also listed by the standard image.
    printf '[uid=0 gid=0 perms=555] lib/libc++.so.2=%s\n' "$cxx_runtime"
    printf '[+optional]\n'
} > "$vm_dir/local/snippets/system_files.shadowdeploy"

cd "$vm_dir"
mkqnximage --type=qemu --arch=x86_64 --hostname=shadowdeploy-qnx \
    --cpu=2 --ram=1G --sys-size=64 --data-size=128 \
    --ssh-ident=none --sshd-pregen=yes --build
for output in output/ifs.bin output/disk-qemu.vmdk output/disk-qemu; do
    if [ ! -s "$output" ]; then
        printf 'Expected image output missing or empty: %s\n' "$output" >&2
        exit 1
    fi
done
printf 'QNX image generated in %s/output. It has not been booted.\n' "$vm_dir"
printf 'Project executables will be in /system/bin/shadowdeploy inside the guest.\n'
